    private void btnIniciarSesionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIniciarSesionActionPerformed
         // Aqui obtengo los datos ingresados
         String userIngresado = this.txtUsuario.getText();
         String passIngresada = new String(this.txtPassword.getPassword());
         // Aqui recupero la lista de usuarios
         ArrayList<Usuario> lista = sistema.getUsuarios();
         boolean accesoConcedido = false;
           // Aqui verifico los usuarios registrados
         for (Usuario u : lista) {

        if (u.getNombreUsuario().equals(userIngresado)
                && u.getContrasena().equals(passIngresada)) {

            accesoConcedido = true;
            break;
        }
    }
         if (accesoConcedido) {

    System.out.println("¡Acceso exitoso al sistema!");

    // Aqui abro la ventana del menu principal
    VentanaMenuPrincipal ventana = new VentanaMenuPrincipal(sistema);
    ventana.setVisible(true);

    // Aqui cierro la ventana de inicio de sesion
    this.dispose();

} else {

    System.out.println("ACCESO DENEGADO: El usuario no tiene acceso o no esta registrado.");
}
    }//GEN-LAST:event_btnIniciarSesionActionPerformed

