    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // Aqui obtengo los datos ingresados
        String id = this.txtIdUsuario.getText();
    String nombre = this.txtNombre.getText();
    String nombreUsuario = this.txtNombreUsuario.getText();
    String contrasena = new String(this.txtPassword.getPassword());
    String correo = this.txtCorreo.getText();
    String telefono = this.txtTelefono.getText();
    String perfil = this.cmbPerfil.getSelectedItem().toString();

    // Aqui verifico que los campos no esten vacios
    if (id.isEmpty() || nombre.isEmpty()
            || nombreUsuario.isEmpty() || contrasena.isEmpty()
            || correo.isEmpty() || telefono.isEmpty()) {

        System.out.println("Debe completar todos los campos.");

    } else {

        // Aqui creo el nuevo usuario
        Usuario nuevo = new Usuario(id, nombre, nombreUsuario,
                contrasena, correo, telefono, perfil);

        // Aqui registro el usuario
        try {
            sistema.registrarUsuario(nuevo);

        } catch (IOException e) {
            System.out.println("Error al guardar el usuario.");
        }
    }
    }//GEN-LAST:event_btnGuardarActionPerformed


