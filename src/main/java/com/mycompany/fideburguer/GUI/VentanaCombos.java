    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // Aqui recupero los datos ingresados
    String id = this.txtIdCombo.getText();
    String nombre = this.txtNombre.getText();
    String descripcion = this.txtDescripcion.getText();
    String precioTexto = this.txtPrecio.getText();

    // Aqui verifico que los campos no esten vacios
    if (id.isEmpty() || nombre.isEmpty()
            || descripcion.isEmpty() || precioTexto.isEmpty()) {

        System.out.println("Debe completar todos los campos.");

    } else {

        // Aqui convierto el precio a float
        float precio = Float.parseFloat(precioTexto);

        // Aqui creo el nuevo combo
        Combo nuevo = new Combo(id, nombre, descripcion, precio);

        // Aqui registro el combo
        try {

            sistema.registrarCombo(nuevo);

        } catch (IOException e) {

            System.out.println("Error al guardar el combo.");
        }
    }
    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void btnConsultarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConsultarActionPerformed
        // Aqui recupero la lista de combos
    List<Combo> lista = sistema.getCombos();

    // Aqui limpio el area de texto
    this.txtAreaCombos.setText("");

    // Aqui verifico si hay combos registrados
    if (lista.isEmpty()) {

        this.txtAreaCombos.setText("No hay combos registrados.");

    } else {

        // Aqui recorro los combos registrados
        for (Combo c : lista) {

            this.txtAreaCombos.append("ID: " + c.getId() + "\n");
            this.txtAreaCombos.append("Nombre: " + c.getNombre() + "\n");
            this.txtAreaCombos.append("Descripcion: " + c.getDescripcion() + "\n");
            this.txtAreaCombos.append("Precio: " + c.getPrecio() + "\n");
            this.txtAreaCombos.append("----------------------------\n");
        }
    }
    }//GEN-LAST:event_btnConsultarActionPerformed

    

