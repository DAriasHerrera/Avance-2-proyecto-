    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // Aqui recupero los datos ingresados
    String id = this.txtIdCombo.getText();
    String nombre = this.txtNombre.getText();
    String descripcion = this.txtDescripcion.getText();
    String precioTexto = this.txtPrecio.getText();

    // Aqui verifico que los campos no esten vacios
    if (id.isEmpty() || nombre.isEmpty()
            || descripcion.isEmpty() || precioTexto.isEmpty()) {

        System.out.println("Debe completar todos los campos.");

    } else {

        // Aqui convierto el precio a float
        float precio = Float.parseFloat(precioTexto);

        // Aqui actualizo el combo registrado
        try {

            sistema.actualizarCombo(id, nombre, descripcion, precio);

        } catch (IOException e) {

            System.out.println("Error al actualizar el combo.");
        }
    }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // Aqui recupero el ID del combo
    String id = this.txtIdCombo.getText();

    // Aqui verifico que se haya ingresado un ID
    if (id.isEmpty()) {

        System.out.println("Debe ingresar el ID del combo.");

    } else {

        // Aqui elimino el combo registrado
        try {

            sistema.eliminarCombo(id);

        } catch (IOException e) {

            System.out.println("Error al eliminar el combo.");
        }
    }
    }//GEN-LAST:event_btnEliminarActionPerformed

